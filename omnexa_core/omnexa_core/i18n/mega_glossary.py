def build_mega_glossary() -> dict[str, str]:
	global _MEGA
	if _MEGA is not None:
		return _MEGA
	g: dict[str, str] = {}
	for src in (WORKSPACE_GLOBAL_AR, _DOMAIN_GLOSSARY, _COMMON_WORDS, FRAGMENT_AR):
		g.update(src)
	# Healthcare catalogs (optional — app may not be installed in all contexts)
	try:
		from omnexa_healthcare.i18n.healthcare_i18n_catalog import JOURNEY_AR, WORKSPACE_AR
		from omnexa_healthcare.i18n.phrase_fix_ar import PHRASE_FIX_AR
		from omnexa_healthcare.i18n.field_ar_bulk import BULK_FIELD_AR

		g.update(WORKSPACE_AR)
		g.update(JOURNEY_AR)
		g.update(PHRASE_FIX_AR)
		g.update(BULK_FIELD_AR)
	except Exception:
		pass
	_MEGA = g
	return g
